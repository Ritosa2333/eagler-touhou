import {readFile, writeFile} from 'node:fs/promises';
import {PRODUCT_GAMES} from '../../common/contracts/product-catalog.mjs';
import {th06SpellStages} from '../../launcher/app/components/launcher/th06-spell-layout.ts';
import {th07SpellStages} from '../../launcher/app/components/launcher/th07-spell-layout.ts';
import {th08SpellGroups} from './th08-spell-layout.mjs';

const dictionaries = await Promise.all(['zh-CN', 'en', 'ja'].map(async language => [
  language,
  JSON.parse(await readFile(new URL('../../launcher/messages/' + language + '.json', import.meta.url))),
]));
const teamKeys = ['barrier', 'magic', 'scarlet', 'ghost'].map(team => 'profile_team_' + team);
const quote = value => JSON.stringify(value).replaceAll('$', '\\$');
const output = [
  '// Generated by tools/generate-progress-catalog.mjs.',
  'const progressRoster = <String, List<({int character, int? shot, Map<String, String> labels})>>{',
];
for (const [game, product] of Object.entries(PRODUCT_GAMES)) {
  const loadouts = product.multiplayer?.loadouts;
  if (!loadouts?.length || game === 'th03') continue;
  const counts = new Map();
  for (const {character} of loadouts) counts.set(character, (counts.get(character) ?? 0) + 1);
  const roster = new Map();
  for (const {character, shot, labelKey, selection} of loadouts) {
    const single = game === 'th075' || counts.get(character) === 1 && shot === 0;
    const keyForLocale = game === 'th08' && teamKeys[character] ? teamKeys[character]
      : (single && (game === 'th075' || game === 'th17') ? selection?.[0]?.labelKey ?? labelKey : labelKey)?.replaceAll('.', '_');
    const labels = dictionaries.flatMap(([language, messages]) => {
      const label = messages[keyForLocale];
      return label ? [quote(language) + ': ' + quote(label.replaceAll(' · ', ' | '))] : [];
    });
    const key = character + ':' + (single ? '-' : shot);
    if (!roster.has(key)) roster.set(key, {character, shot: single ? null : shot, labels});
  }
  output.push('  ' + quote(game) + ': [');
  for (const {character, shot, labels} of roster.values()) {
    output.push('    (character: ' + character + ', shot: ' + shot + ', labels: {' + labels.join(', ') + '}),');
  }
  output.push('  ],');
}
output.push('};', '');
output.push(
  'typedef SpellLayoutCard = ({int number, int nameLength, bool midboss});',
  'typedef SpellStageLayout = ({int stage, List<SpellLayoutCard> cards});',
  '',
  'const spellStageCatalog = <String, Map<String, List<SpellStageLayout>>>{',
);
const th08SpellStages = level => (th08SpellGroups[level] ?? []).map(([stage, entries]) => ({
  stage,
  cards: entries.map(([number, nameLength]) => ({number, nameLength, midboss: false})),
}));
for (const [game, layout] of [['th06', th06SpellStages], ['th07', th07SpellStages], ['th08', th08SpellStages]]) {
  output.push('  ' + quote(game) + ': {');
  for (const level of ['easy', 'normal', 'hard', 'lunatic', 'extra', 'phantasm', 'last-word']) {
    const stages = layout(level);
    if (!stages.length) continue;
    output.push('    ' + quote(level) + ': [');
    for (const {stage, cards} of stages) {
      output.push('      (stage: ' + stage + ', cards: [');
      for (const {number, nameLength, midboss} of cards) {
        output.push('        (number: ' + number + ', nameLength: ' + nameLength + ', midboss: ' + midboss + '),');
      }
      output.push('      ]),');
    }
    output.push('    ],');
  }
  output.push('  },');
}
output.push('};', '');
await writeFile(new URL('../lib/game_progress_catalog.dart', import.meta.url), output.join('\n'));
