import {copyFile, mkdir, readFile, writeFile} from 'node:fs/promises';
import {QUICK_CHAT_PHRASES} from '../../common/contracts/multiplayer-quick-chat.mjs';

const japanese = JSON.parse(await readFile(
  new URL('../../launcher/messages/ja.json', import.meta.url), 'utf8',
));
const extraJapanese = {
  wait: '少し待ってください',
  sorry: '申し訳ありません',
  continue: '続けましょう',
  lagging: 'ラグがあります',
  'no-worries': '大丈夫です',
  laugh: '面白いですね',
  retry: 'もう一度やりますか？',
  'no-no': 'No no no no',
  'yes-yes': 'Yes yes',
  ah: 'あぁー',
  'move-right': '少し右へ移動してください',
  'move-left': '少し左へ移動してください',
  busy: '用事ができました',
  'you-first': '先に選んでください',
  nice: 'ナイス',
  amazing: 'すごいですね',
  'great-opportunity': '絶好のチャンスですね',
  'feels-good': '気持ちいいですね',
};
const dartString = value => JSON.stringify(value).replaceAll('$', '\\$');
const rows = QUICK_CHAT_PHRASES.map(({id, zh, en}) => {
  const ja = japanese['chat_phrase_'+id.replaceAll('-', '_')] ?? extraJapanese[id];
  if (!ja) throw new Error('Missing Japanese quick-chat phrase: '+id);
  return '  '+dartString(id)+': (zh: '+dartString(zh)+', en: '+dartString(en)+', ja: '+dartString(ja)+'),';
});
const input = new URL('../../launcher/public/assets/quick-chat/', import.meta.url);
const output = new URL('../assets/quick-chat/', import.meta.url);
await mkdir(output, {recursive: true});
await Promise.all(QUICK_CHAT_PHRASES.map(({id}) =>
  copyFile(new URL(id+'.wav', input), new URL(id+'.wav', output)),
));
await writeFile(new URL('../lib/room_phrases.dart', import.meta.url), [
  '// Generated by tools/generate-room-phrases.mjs.',
  '',
  'typedef RoomPhrase = ({String zh, String en, String ja});',
  '',
  'String roomPhraseLabel(RoomPhrase phrase, String language) => switch (language) {',
  "  'en' => phrase.en,",
  "  'ja' => phrase.ja,",
  '  _ => phrase.zh,',
  '};',
  '',
  'const roomPhrases = <String, RoomPhrase>{',
  ...rows,
  '};',
  '',
].join('\n'));
