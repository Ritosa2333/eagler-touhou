const { chmodSync, mkdirSync, writeFileSync } = require('node:fs');
const { dirname, resolve } = require('node:path');

function fail(message) {
  throw new Error(message);
}

function envRaw(name, legacyName) {
  const configured = [name, legacyName]
    .filter(Boolean)
    .filter(key => process.env[key] != null)
    .map(key => [key, String(process.env[key])]);
  if (configured.length > 1 && new Set(configured.map(([, value]) => value)).size > 1)
    fail(`conflicting environment variables: ${configured.map(([key]) => key).join(', ')}`);
  return configured[0]?.[1] || '';
}

function envText(name, legacyName, { required = false } = {}) {
  const value = envRaw(name, legacyName).trim();
  if (required && !value) fail(`${name} is required`);
  if (/\r|\n/.test(value)) fail(`${name} must not contain newlines`);
  return value;
}

function envInt(name, legacyName, fallback, min, max) {
  const raw = envRaw(name, legacyName).trim();
  if (!raw) return fallback;
  if (!/^\d+$/.test(raw)) fail(`${name} must be an integer in ${min}..${max}`);
  const value = Number(raw);
  if (!Number.isSafeInteger(value) || value < min || value > max)
    fail(`${name} must be an integer in ${min}..${max}`);
  return value;
}

function outputPath() {
  const index = process.argv.indexOf('--output');
  if (index < 0 || !process.argv[index + 1])
    fail('usage: node render-coturn-config.cjs --output PATH');
  return resolve(process.argv[index + 1]);
}

const realm = envText('EAGLER_NETPLAY_TURN_REALM', 'TH07_TURN_REALM', { required: true });
const secret = envText('EAGLER_NETPLAY_TURN_SHARED_SECRET', 'TH07_TURN_SHARED_SECRET', { required: true });
if (Buffer.byteLength(secret, 'utf8') < 24)
  fail('EAGLER_NETPLAY_TURN_SHARED_SECRET must be at least 24 bytes');

const listeningPort = envInt('EAGLER_NETPLAY_TURN_LISTENING_PORT', 'TH07_TURN_LISTENING_PORT', 3478, 1, 65535);
const tlsListeningPort = envInt('EAGLER_NETPLAY_TURN_TLS_LISTENING_PORT', 'TH07_TURN_TLS_LISTENING_PORT', 5349, 1, 65535);
const minPort = envInt('EAGLER_NETPLAY_TURN_MIN_PORT', 'TH07_TURN_MIN_PORT', 49152, 1024, 65535);
const maxPort = envInt('EAGLER_NETPLAY_TURN_MAX_PORT', 'TH07_TURN_MAX_PORT', 65535, 1024, 65535);
if (minPort > maxPort) fail('EAGLER_NETPLAY_TURN_MIN_PORT must not exceed EAGLER_NETPLAY_TURN_MAX_PORT');

// Intentionally conservative defaults for the current ~10 Mbps VPS. Touhou
// netplay is far below these limits; they mainly bound accidental/hostile use.
const userQuota = envInt('EAGLER_NETPLAY_TURN_USER_QUOTA', 'TH07_TURN_USER_QUOTA', 12, 1, 10000);
const totalQuota = envInt('EAGLER_NETPLAY_TURN_TOTAL_QUOTA', 'TH07_TURN_TOTAL_QUOTA', 256, 1, 1000000);
const maxBps = envInt('EAGLER_NETPLAY_TURN_MAX_BPS', 'TH07_TURN_MAX_BPS', 131072, 1024, 1000000000);
const bpsCapacity = envInt('EAGLER_NETPLAY_TURN_BPS_CAPACITY', 'TH07_TURN_BPS_CAPACITY', 786432, 1024, 1000000000);

const listeningIp = envText('EAGLER_NETPLAY_TURN_LISTENING_IP', 'TH07_TURN_LISTENING_IP');
const relayIp = envText('EAGLER_NETPLAY_TURN_RELAY_IP', 'TH07_TURN_RELAY_IP');
const externalIp = envText('EAGLER_NETPLAY_TURN_EXTERNAL_IP', 'TH07_TURN_EXTERNAL_IP');
const cert = envText('EAGLER_NETPLAY_TURN_CERT', 'TH07_TURN_CERT');
const pkey = envText('EAGLER_NETPLAY_TURN_PKEY', 'TH07_TURN_PKEY');
if (!!cert !== !!pkey) fail('EAGLER_NETPLAY_TURN_CERT and EAGLER_NETPLAY_TURN_PKEY must be configured together');

const lines = [
  '# Generated by server/render-coturn-config.cjs',
  '# Do not commit the rendered file: it contains EAGLER_NETPLAY_TURN_SHARED_SECRET.',
  `listening-port=${listeningPort}`,
  `min-port=${minPort}`,
  `max-port=${maxPort}`,
  'fingerprint',
  'use-auth-secret',
  `static-auth-secret=${secret}`,
  `realm=${realm}`,
  'no-cli',
  'no-multicast-peers',
  'no-dtls',
  `user-quota=${userQuota}`,
  `total-quota=${totalQuota}`,
  `max-bps=${maxBps}`,
  `bps-capacity=${bpsCapacity}`,
  '',
  '# Do not let TURN clients use this VPS as a path into private/reserved IPv4 networks.',
  'denied-peer-ip=0.0.0.0-0.255.255.255',
  'denied-peer-ip=10.0.0.0-10.255.255.255',
  'denied-peer-ip=100.64.0.0-100.127.255.255',
  'denied-peer-ip=127.0.0.0-127.255.255.255',
  'denied-peer-ip=169.254.0.0-169.254.255.255',
  'denied-peer-ip=172.16.0.0-172.31.255.255',
  'denied-peer-ip=192.0.0.0-192.0.0.255',
  'denied-peer-ip=192.0.2.0-192.0.2.255',
  'denied-peer-ip=192.88.99.0-192.88.99.255',
  'denied-peer-ip=192.168.0.0-192.168.255.255',
  'denied-peer-ip=198.18.0.0-198.19.255.255',
  'denied-peer-ip=198.51.100.0-198.51.100.255',
  'denied-peer-ip=203.0.113.0-203.0.113.255',
  'denied-peer-ip=240.0.0.0-255.255.255.255',
];

if (listeningIp) lines.push(`listening-ip=${listeningIp}`);
if (relayIp) lines.push(`relay-ip=${relayIp}`);
if (externalIp) lines.push(`external-ip=${externalIp}`);

if (cert) {
  lines.push(
    `tls-listening-port=${tlsListeningPort}`,
    `cert=${cert}`,
    `pkey=${pkey}`,
    'no-tlsv1',
    'no-tlsv1_1',
  );
} else {
  // TURN/UDP and TURN/TCP remain available on listening-port. TURN/TLS is
  // enabled only when a real certificate/private-key pair is supplied.
  lines.push('no-tls');
}

const output = outputPath();
mkdirSync(dirname(output), { recursive: true });
writeFileSync(output, `${lines.join('\n')}\n`, { mode: 0o600 });
try { chmodSync(output, 0o600); } catch {}
console.log(`coturn config written: ${output}`);
