"""Generate the native translation table shared by Windows and Web builds."""
from pathlib import Path
import json, argparse
root=Path(__file__).resolve().parents[1]
def generate(check=False):
    rows=json.loads((root/'portable/locales.json').read_text(encoding='utf-8'))
    keys=set()
    for row in rows:
        if len(row)!=3 or not all(isinstance(v,str) and v for v in row) or row[0] in keys:
            raise ValueError('Invalid or duplicate translation: '+repr(row))
        keys.add(row[0])
    for i in range(1,10):rows.append([f'阶段 {i}',f'Phase {i}',f'段階 {i}'])
    for source,en,ja in [('人偶展开','Doll deployment','人形展開'),('护盾','Shield','シールド')]:
        for i in range(1,4):rows.append([f'{source} {i}',f'{en} {i}',f'{ja} {i}'])
    for source,en,ja in [('舞','Mai','舞'),('雪','Yuki','雪')]:
        for i in range(1,5):rows.append([f'{source} - 阶段 {i}',f'{en} - Phase {i}',f'{ja} - 段階 {i}'])
    data='// Generated by scripts/generate-locales.py from portable/locales.json.\n'+''.join('{'+','.join('u8'+json.dumps(v,ensure_ascii=True) for v in row)+'},\n' for row in rows)
    target=root/'portable/LocalizationTable.inc'
    if check:
        if target.read_text(encoding='utf-8')!=data:raise ValueError('Translation table is stale')
    else:target.write_text(data,encoding='utf-8')
if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');generate(parser.parse_args().check)
