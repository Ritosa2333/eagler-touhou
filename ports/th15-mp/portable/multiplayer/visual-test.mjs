import {spawnSync} from 'node:child_process';
import {readFileSync,writeFileSync,readdirSync,existsSync} from 'node:fs';
import {resolve,basename} from 'node:path';
const root=resolve(import.meta.dirname,'../..');
const sdk=resolve(process.env.TH15_EMSDK||resolve(root,'tools/emsdk'));
const compiler=['install','upstream'].map(p=>resolve(sdk,p,'emscripten/emcc.py')).find(existsSync);
if(!compiler)throw Error('Set TH15_EMSDK');
const out=resolve(root,'web',process.env.TH15_OUTPUT||'artifacts/sdl-multiplayer');
const build=JSON.parse(readFileSync(resolve(out,'build.json')));
const run=(program,args)=>{const r=spawnSync(program,args,{cwd:root,env:{...process.env,EM_CONFIG:resolve(sdk,'.emscripten'),TEMP:out,TMP:out},encoding:'utf8',windowsHide:true,maxBuffer:4*1024*1024});if(r.error)throw r.error;if(r.status)throw Error(r.stdout+r.stderr);if(r.stdout)process.stdout.write(r.stdout);return r;};
const flags=['-O2','-std=c++17','-DTH_NATIVE_PLATFORM=1','-DTH15_MULTIPLAYER=1','-DTH_ENABLE_THPRAC=0','-ffp-contract=off','-fno-strict-aliasing','-fno-exceptions','-fno-rtti','-I'+resolve(root,'../../common/include')];
const fixture=resolve(out,'visual-gameplay.o');run('python',[compiler,...flags,'-c',resolve(import.meta.dirname,'visual-gameplay.cpp'),'-o',fixture]);
const sources=Object.keys(build.sources),journal=build.netplay?.stateBackend==='write-journal-32';
const dependencies=['WriteJournal.cpp','SimulationHeap.cpp'].flatMap(name=>{
 const matches=sources.filter(p=>basename(p)===name);
 if(matches.length>1||(journal&&matches.length!==1))throw Error('Expected one production '+name+' object in build.sources');
 return matches;
});
const objects=[...sources.filter(p=>p.startsWith('web/cpp/game/')),...dependencies].map(p=>resolve(out,'objects',p.replaceAll('/','_')+'.o'));
for(const object of objects)if(!existsSync(object))throw Error('Missing production object: '+object);
const loader=resolve(out,'visual-gameplay.cjs'),rsp=resolve(out,'visual-test.rsp');
writeFileSync(rsp,[...flags,'--use-port=sdl3','-sDEFAULT_TO_CXX=1','-sENVIRONMENT=node','-sNODERAWFS=1','-sEXIT_RUNTIME=1','-sALLOW_MEMORY_GROWTH=1','-sSTACK_SIZE=8388608','-sINITIAL_MEMORY=134217728','-sMAXIMUM_MEMORY=1073741824',...objects,fixture,'-o',loader].map(a=>JSON.stringify(a)).join('\n'));
run('python',[compiler,'@'+rsp]);
if(!process.env.TH15_TEST_ARCHIVE)throw Error('Set TH15_TEST_ARCHIVE to the Japanese 1.00b archive');
const result=run(process.execPath,[loader,resolve(process.env.TH15_TEST_ARCHIVE)]);
writeFileSync(resolve(out,'visual-test-result.json'),result.stdout);
