import assert from 'node:assert/strict';
import {encodeTape,decodeTape,validateTape,VERSION} from '../web/replay/tape.js';
const header={version:VERSION,game:'03',adapter:'confirmed-worker/1',players:2,hostSlot:0,tickMs:1000/60,settings:{},identity:'a'.repeat(64),opening:{}};
const input={actions:[],touch:0,focusEnabled:true,points:false,commands:[]};
const rows=Array.from({length:4},()=>({inputs:[input,input],offlineMask:0,proof:'',hash:null}));
const tape={header,rows,matchStart:2,end:{frame:4,reason:'对局结束'}};
const decoded=await decodeTape(await encodeTape(tape));
assert.deepEqual(decoded,tape);
for(const start of [-1,4,1.5,undefined])assert.throws(()=>validateTape({...tape,matchStart:start}));
assert.throws(()=>validateTape({...tape,end:{frame:3,reason:'end'}}));
console.log('TH03 battle replay format PASS');
