import {readFileSync as read,writeFileSync as write} from 'node:fs';
import {resolve} from 'node:path';
import {createHash} from 'node:crypto';
const [source,defs,license,retail,cpp,js]=process.argv.slice(2);
if(!js)throw Error('Usage: generate-th14-practice.mjs THPRAC_TH14_CPP GAMES_JSON LICENSE RETAIL_ECL_DIR CPP_OUTPUT_DIR UI_LABELS_INC');
const s=read(source,'utf8').replaceAll('\r\n','\n'), d=JSON.parse(read(defs,'utf8').replace(/^\uFEFF/,'')), g=d.th14;
const sectionKeys=Object.keys(g.sections), glossary=Object.assign({},...Object.values(d).map(x=>x.glossary));
const cases=(a,b)=>new Set([...s.slice(s.indexOf(a),s.indexOf(b,s.indexOf(a)+1)).matchAll(/case (TH14_\w+):/g)].map(x=>x[1]));
const dialogue=cases('bool SectionHasDlg','bool SectionHasSpellDrops'), drops=cases('bool SectionHasSpellDrops','void SectionWidget');
const alias=key=>key.replace(/^TH14_ST4[AB]_/, 'TH14_ST4_');
const sha=createHash('sha256').update(s).digest('hex');
const banner='// Adapted from thprac_purple (MIT, copyright Ack). See PracticeLicenseTh14.txt.\n// thprac_th14.cpp SHA-256 (LF): '+sha+'\n';
let code=s.slice(s.indexOf('    void ECLJump('),s.indexOf('    __declspec(noinline) void THSectionPatch()'))
 .replaceAll('        ecl.SetPos(start);','        ecl.Jump(start, dest);\n        ecl.SetPos(start);')
 .replace('    constexpr unsigned int st7PostMaple','    static constexpr unsigned int st7PostMaple')
 .replaceAll('__declspec(noinline) ','').replaceAll('THPrac::TH14::','').replaceAll('th_sections_t','i32')
 .replace('void THPatchSP(ECLHelper& ecl)\n    {\n        uint32_t spell_id = *(int32_t*)(0x4f5844);','void THPatchSP(ECLHelper& ecl, i32 spell_id)\n    {');
if(/GetMem|0x4f5844|__declspec|THPrac::/.test(code))throw Error('Unmapped platform dependency');
write(resolve(cpp,'PracticePatchesTh14.inc'),banner+code.replace(/[ \t]+$/gm,'').trimEnd()+'\n');
write(resolve(cpp,'PracticeLicenseTh14.txt'),read(license));
const phase={TH14_ST3_MID2_HL:2,TH14_ST6_BOSS8:2,TH14_ST6_BOSS9:2,TH14_ST6_BOSS10:4,TH14_ST7_END_S9:2,TH14_ST7_END_S10:5};
let catalog=sectionKeys.map((key,i)=>{const v=g.sections[key], stage=v.appearance[0];return {
 id:i+1,key,stage:stage>7?4:stage,variant:stage>7?stage-7:0,bgm:v.bgm||0,group:v.appearance[1],spell:!!v.spell,timeout:key==='TH14_ST3_MID2_HL'||key==='TH14_ST7_END_S9',
 dialogue:dialogue.has(alias(key)),drops:drops.has(alias(key)),phases:phase[alias(key)]??1,angle:key==='TH14_ST6_BOSS8',
 labels:[...'ENHLX'].map(rank=>{const entry=Object.entries(v).find(([k])=>k[0]==='!'&&k.includes(rank))?.[1];return Array.isArray(entry)?entry:glossary[entry]??['','',''];})
}});
const index=new Map(sectionKeys.map((k,i)=>[k,i+1]));
const used=[...new Set([...code.matchAll(/case (TH14_\w+):/g)].map(x=>x[1]))];
for(const k of used)if(!index.has(k)){const a=sectionKeys.find(x=>alias(x)===k);if(!a)throw Error(k);index.set(k,index.get(a));}
const normalize=id=>{const v=catalog[id-1], k=alias(v.key); return used.includes(k)?index.get(k):0};
catalog=catalog.map(v=>({...v,native:normalize(v.id)})).filter(v=>v.native);
const fnv=b=>{let x=14695981039346656037n;for(const a of b)x=BigInt.asUintN(64,(x^BigInt(a))*1099511628211n);return '0x'+x.toString(16)+'ull'};
let tables=[];
for(let n=1;n<=7;n++){
 const base='st0'+n+'.ecl', b=read(resolve(retail,base)), off=b.indexOf('ECLI'), count=b.readUInt32LE(off+4);
 const inc=b.subarray(off+8).toString('latin1').split('\0').slice(0,count);
 const names=[base,...inc];
 tables.push('{'+names.map(name=>fnv(read(resolve(retail,name)))).join(',')+'}');
}
write(resolve(cpp,'PracticeCatalogTh14.inc'),banner+'enum {\n'+used.map(k=>'    '+k+' = '+index.get(k)+',').join('\n')+'\n};\n'+
 'constexpr u64 retail_ecl[7][6] = {\n    '+tables.join(',\n    ')+'\n};\n'+
 'constexpr Section sections[] = {\n'+catalog.map(v=>'    {'+[v.id,v.native,v.stage,v.bgm,v.phases,v.dialogue,v.drops,[...v.labels].reduce((a,l,i)=>a|(+!!l[0]<<i),0)].join(',')+'},').join('\n')+'\n};\n');
write(js,'// Generated by tools/generate-th14-practice.mjs.\nconstexpr Item practice_labels[]={\n'+catalog.map(s=>{
 const labels='{'+s.labels.map(names=>'{'+names.map(x=>JSON.stringify(x)).join(',')+'}').join(',')+'}';
 return '    {'+[s.id,s.stage,s.variant,s.phases,s.group,s.dialogue,s.drops,s.angle,s.timeout,s.spell,labels].join(',')+'},';
}).join('\n')+'\n};\n');
