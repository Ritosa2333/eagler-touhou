const assert = require('node:assert/strict');
require('./netplay-audio-probe.cjs');
const probe=globalThis.createNetplayAudioProbe();
let originalCalls=0;
const samples=new Float32Array(4096);
const node={onaudioprocess(){++originalCalls;samples[0]=.25;return 'original-result';}};
const sdl={audioContext:{state:'running',currentTime:0},audio_playback:{scriptProcessorNode:node}};
const event={outputBuffer:{numberOfChannels:2,getChannelData:()=>samples}};
probe.observe(sdl,true);probe.observe(sdl,true);
assert.equal(node.onaudioprocess(event),'original-result');
assert.equal(originalCalls,1,'do not wrap twice or replace the callback');
sdl.audioContext.currentTime=1;probe.observe(sdl,true);
assert.equal(probe.snapshot().progressedSeconds,1);
assert.equal(probe.snapshot().nonzeroBlocks,1);
assert.equal(probe.snapshot().maxAmplitude,.25);
assert.equal(probe.snapshot().sampledValues,64);
probe.observe(sdl,false);node.onaudioprocess(event);
assert.equal(originalCalls,2);
assert.equal(probe.snapshot().blocks,1,'exclude unmeasured startup/shutdown');
console.log('PASS audio observer: original callback, running clock, nonzero output, bounded sampling');
