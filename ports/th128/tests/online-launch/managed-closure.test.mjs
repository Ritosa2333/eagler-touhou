import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {buildOnlineSite,SITE_FILES} from '../../tools/package-online-site.mjs';
const hash=b=>createHash('sha256').update(b).digest('hex');
test('static source assembly includes the managed DATA owner required by the current entry',t=>{
 const root=fs.mkdtempSync(path.join(os.tmpdir(),'th128-managed-closure-'));
 assert.equal(path.dirname(root),path.resolve(os.tmpdir()));
 t.after(()=>fs.rmSync(root,{recursive:true,force:true}));
 const write=(name,bytes)=>{const file=path.join(root,name);fs.mkdirSync(path.dirname(file),{recursive:true});fs.writeFileSync(file,bytes);};
 for(const name of SITE_FILES)write('site/'+name,'source:'+name);
 const moduleBytes=Buffer.from('export async function bindManagedDatProvider(){return null;}\n');
 write('site/runtime/managed-dat-owner.mjs',moduleBytes);
 const generation='c'.repeat(64),js=Buffer.from('export default()=>{};\n'),wasm=Buffer.from('synthetic-not-executed');
 write('core/site/runtime/builds/'+generation+'/core.mjs',js);write('core/site/runtime/builds/'+generation+'/core.wasm',wasm);
 write('core/site/runtime/build.json',JSON.stringify({game:'th128',privateCore:112,generation,entry:'runtime/builds/'+generation+'/core.mjs',artifacts:{'core.mjs':{bytes:js.length,sha256:hash(js)},'core.wasm':{bytes:wasm.length,sha256:hash(wasm)}},exports:205,packageDataLayout:'sha256-58cd45fe7cac9af281d9de993a527ccfbbe6f27b89bcd0ca98a7031333fce200'}));
 write('site/runtime/online-resources.mjs','online-module');const zip=Buffer.from('tiny synthetic archive');
 write('resource.zip',zip);
 const output=path.join(root,'out');
 const result=buildOnlineSite({siteRoot:path.join(root,'site'),coreRoot:path.join(root,'core'),coreBuild:generation,resourceZip:path.join(root,'resource.zip'),outputRoot:output,packageManifest:{authority:'MAIN',ordinal:674,revision:'0123456789abcdef',zipBytes:zip.length,zipSha256:hash(zip)}});
 const file=path.join(output,'runtime/managed-dat-owner.mjs');
 assert.equal(fs.existsSync(file),true,'Current managed entry dependency is missing from the assembled source tree');
 assert.deepEqual(fs.readFileSync(file),moduleBytes);
 const row=result.files.find(row=>row.path==='runtime/managed-dat-owner.mjs');
 assert.equal(row.sha256,hash(moduleBytes));assert.equal(row.bytes,moduleBytes.length);
});
