import assert from 'node:assert/strict';
import test from 'node:test';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
test('actual stage_a1 STD supplies geometry, repeated placements and authored timed camera/fog',async()=>{
 assert.ok(fs.existsSync(path.join(root,'site/runtime/background.mjs')),'actual STD background runner missing');
 const {parseStd,StageCamera}=await import('../site/runtime/background.mjs');
 const catalog=JSON.parse(fs.readFileSync(path.join(root,'local/catalog.json'))),directory=path.dirname(path.join(root,'local',catalog.variants.ja.manifest));
 const bytes=fs.readFileSync(path.join(directory,'raw/stage_a1.std')),data=parseStd(bytes);
 assert.equal(data.anm,'stage_a1.anm');assert.equal(data.objects.length,3);assert.equal(data.instances.length,16);
 assert.deepEqual(data.objects.map(object=>object.quads.length),[3,2,2]);
 assert.equal(data.commands[0].opcode,6);assert.equal(data.commands.find(command=>command.opcode===10).integers[0],690);
 const camera=new StageCamera(data),initial=camera.snapshot();
 assert.deepEqual(initial.up,[0,1,0]);assert.equal(initial.fov,Math.fround(Math.PI/5));
 for(let tick=0;tick<120;++tick)camera.tick();const moving=camera.snapshot();
 assert.notDeepEqual(moving.position,initial.position);assert.notDeepEqual(moving.fog,initial.fog);
 assert.deepEqual(camera.snapshot(),moving,'drawing snapshots cannot advance the camera');
 for(let tick=120;tick<3300;++tick)camera.tick();assert.equal(camera.snapshot().frame,3300);
 for(const length of [0,4,143,400,1300])assert.throws(()=>parseStd(bytes.subarray(0,length)));
 const invalid=Buffer.from(bytes);invalid.writeUInt32LE(0xfffffff0,8);assert.throws(()=>parseStd(invalid));
});
