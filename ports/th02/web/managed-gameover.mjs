// The original Game Over caption waits indefinitely for an extra key before
// presenting Continue. Keep its animation and remove only that wait loop.
export function installGameOverTransition(exe){
  const header=exe[8]*16+exe[9]*4096,at=header+0xc3f3;
  const expected=[0xc7,0x06,0x38,0x25,0,0,0xeb,0x05,0x9a,0xde,0x01,0x45,0x0f,0x83,0x3e,0x38,0x25,0,0x74,0xf4];
  if(!expected.every((byte,i)=>exe[at+i]===byte))throw Error('TH02 Game Over 原程序不匹配');
  exe[at+18]=0x90;exe[at+19]=0x90;
}

export function installNativeMarker(exe,patch){
  const cs=patch.headerSize+patch.codeSegment*16;
  for(const [offset,expected] of [[0x4edd,[0xe8,0x95,0x29]],[0x7885,[0x89,0xe9,0xb8,0x01,0x00]],[0x78ef,[0xb8,0x00,0xa8]]])if(!expected.every((byte,i)=>exe[cs+offset+i]===byte))throw Error('TH02 原生判定点补丁不匹配');
  // Execute the same drawing path on every peer, masking only VRAM writes.
  // Block interrupts while the local mask is in registers so saved CPU state stays identical.
  exe.set([0xeb,0x26,0x9c,0x2e,0x0f,0xa3,0x2e,0x33,0x86,0x19,0xc0,0x21,0xc3,0x9d,0xb8,0x00,0xa8,0xc3],cs+0x7885);
  exe.set([0x9c,0xfa,0xe8,0xd8,0xff,0x9d,0xc3],cs+0x7898);
  exe.set([0xe8,0x95,0xff],cs+0x78ef);
  exe.set([0xe8,0xb8,0x29],cs+0x4edd);
}
